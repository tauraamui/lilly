module main

import strings

const header_note = '// Code generated by cmd/syntaxgen. DO NOT EDIT.'

// Gen turns one grammar into V code. Every name it emits starts with
// `lex_<id>_`, so all the generated lexers share module syntax.
struct Gen {
	g      Grammar
	prefix string
mut:
	out strings.Builder
	// fns holds the pattern matchers, written after the contexts
	fns      []string
	fn_count int
	// uses_emit lists the contexts whose function takes `emit`, by index
	uses_emit map[int]bool
	// embedded_emit says, for each grammar this one embeds, which of its
	// contexts' functions take `emit`
	embedded_emit map[string][]bool
	// pattern_fns reuses one matcher for patterns with the same structure
	pattern_fns map[string]string
}

// Generated is one grammar's lexer source
struct Generated {
	code string
	// takes_emit is set when the lexer's step function takes `emit`
	takes_emit bool
	// context_emit says which contexts' functions take `emit`
	context_emit []bool
}

// generate generates a grammar's lexer. `embedded_emit` gives, for each
// grammar it embeds, which of that grammar's context functions take `emit`.
fn generate(g Grammar, license string, embedded_emit map[string][]bool) !Generated {
	mut gen := Gen{
		g:             g
		prefix:        'lex_${g.id}_'
		out:           strings.new_builder(64 * 1024)
		embedded_emit: embedded_emit
	}
	gen.out.write_string(license)
	gen.out.write_string('\n${header_note}\n// Source: lib/syntax/grammars/${g.id}.kdl\n\nmodule syntax\n\n')
	gen.syntax_const()
	gen.info_const()
	// the contexts are generated first, so the step function knows which
	// of them take `emit`
	mut contexts := strings.new_builder(64 * 1024)
	for ci, ctx in g.contexts {
		if copy := ctx.copy {
			contexts.write_string(gen.copy_fn(ci, copy)!)
			continue
		}
		contexts.write_string(gen.context_fn(ci)!)
	}
	gen.step_fn()
	gen.out.write_string(contexts.str())
	if g.words.len > 0 {
		gen.words_fn()
	}
	for f in gen.fns {
		gen.out.write_string(f)
	}
	return Generated{
		code:         gen.out.str()
		takes_emit:   gen.uses_emit.len > 0
		context_emit: []bool{len: g.contexts.len, init: gen.uses_emit[index]}
	}
}

// ctx_fn_name names a context's function. Copies of an embedded grammar's
// contexts are named for their embed too, as their names can repeat.
fn (gen Gen) ctx_fn_name(index int) string {
	ctx := gen.g.contexts[index]
	if copy := ctx.copy {
		return '${gen.prefix}ctx_e${copy.embed}_${ctx.name}'
	}
	return '${gen.prefix}ctx_${ctx.name}'
}

fn (mut gen Gen) syntax_const() {
	mut keywords := []string{}
	mut literals := []string{}
	mut builtins := []string{}
	for word in sorted_keys(gen.g.words) {
		scope := gen.g.words[word]
		match scope.all_before('.') {
			'keyword' { keywords << word }
			'literal' { literals << word }
			'builtin' { builtins << word }
			else {}
		}
	}
	gen.out.writeln('const ${gen.prefix}syntax = Syntax{')
	gen.out.writeln('\tname: ${v_str(gen.g.name)}')
	gen.out.writeln('\textensions: ${v_str_array(gen.g.extensions)}')
	gen.out.writeln('\tkeywords: ${v_str_array(keywords)}')
	gen.out.writeln('\tliterals: ${v_str_array(literals)}')
	gen.out.writeln('\tbuiltins: ${v_str_array(builtins)}')
	gen.out.writeln('\tlang: .${gen.g.id}')
	gen.out.writeln('}\n')
}

fn (mut gen Gen) info_const() {
	names := gen.g.contexts.map(v_str(it.name))
	scopes := gen.g.contexts.map('Scope.' + scope_ident(it.scope))
	eol := gen.g.contexts.map(it.pops_at_eol.str())
	gen.out.writeln('const ${gen.prefix}info = LangInfo{')
	gen.out.writeln('\tnames: [${names.join(', ')}]')
	gen.out.writeln('\tscopes: [${scopes.join(', ')}]')
	gen.out.writeln('\tpops_at_eol: [${eol.join(', ')}]')
	gen.out.writeln('}\n')
}

fn (mut gen Gen) step_fn() {
	params := if gen.uses_emit.len > 0 {
		'ctx u8, r []rune, i int, emit bool'
	} else {
		'ctx u8, r []rune, i int'
	}
	gen.out.writeln('fn ${gen.prefix}step(${params}) Match {')
	gen.out.writeln('\treturn match ctx {')
	for i in 0 .. gen.g.contexts.len {
		args := if gen.uses_emit[i] { 'r, i, emit' } else { 'r, i' }
		gen.out.writeln('\t\t${i} { ${gen.ctx_fn_name(i)}(${args}) }')
	}
	gen.out.writeln('\t\telse { Match{\n\t\t\tnext: i + 1\n\t\t} }')
	gen.out.writeln('\t}')
	gen.out.writeln('}\n')
}

// copy_fn emits the function for a copy of an embedded grammar's context: the
// escape, then the embedded grammar's own function for the context, with the
// contexts its rules go to moved along to their copies. Where it finds plain
// text, the plain text stops short of anywhere the escape could start.
fn (mut gen Gen) copy_fn(index int, copy Copy) !string {
	embed := gen.g.embeds[copy.embed]
	src_emit := gen.embedded_emit[embed.lang] or {
		return error('embedded grammar "${embed.lang}" has to be generated first')
	}
	takes_emit := src_emit[copy.source]
	if takes_emit {
		gen.uses_emit[index] = true
	}
	escape := parse_pattern(embed.escape)!
	first := first_of(escape)
	bol := starts_at_bol(escape)
	mut guards := []string{}
	if bol {
		guards << 'i == 0'
	}
	if !first.any {
		guards << or_join(first.classes.map(class_cond(it, 'r[i]')))
	}
	escape_fn := gen.pattern_fn(escape)
	mut out := strings.new_builder(2048)
	out.writeln('// context ${gen.g.contexts[index].name}, ${embed.lang} embedded until ${embed.escape.replace('\n', ' ')}')
	out.writeln('@[direct_array_access]')
	params := if takes_emit { 'r []rune, i int, emit bool' } else { 'r []rune, i int' }
	out.writeln('fn ${gen.ctx_fn_name(index)}(${params}) Match {')
	out.writeln(guarded_block(guards))
	out.writeln('\t\te := ${escape_fn}(r, i)')
	out.writeln('\t\tif e >= 0 {')
	out.writeln('\t\t\treturn Match{')
	out.writeln('\t\t\t\tend: e')
	out.writeln('\t\t\t\tscope: .${scope_ident(embed.scope)}')
	out.writeln('\t\t\t\top: .escape')
	out.writeln('\t\t\t\ttarget: ${embed.root}')
	out.writeln('\t\t\t}')
	out.writeln('\t\t}')
	out.writeln('\t}')
	args := if takes_emit { 'r, i, emit' } else { 'r, i' }
	out.writeln('\tm := lex_${embed.lang}_ctx_${copy.source_name}(${args})')
	if !bol {
		// plain text runs up to where the escape could next start
		out.writeln('\tif m.end < 0 {')
		out.write_string(plain_text_before(first))
		out.writeln('\t}')
	}
	out.writeln('\tif m.op == .push || m.op == .set {')
	out.writeln('\t\treturn Match{\n\t\t\t...m\n\t\t\ttarget: m.target + ${embed.root}\n\t\t}')
	out.writeln('\t}')
	out.writeln('\treturn m')
	out.writeln('}\n')
	return out.str()
}

// guarded_block opens the block a rule or escape is tried in: an `if` on
// `guards`, or with none, a bare block
fn guarded_block(guards []string) string {
	if guards.len == 0 {
		return '\t{'
	}
	return '\tif ${and_join(guards)} {'
}

// plain_text_before is the return of the plain text a copied context finds,
// running up to the next rune the escape, which starts with `first`, could
// start at
fn plain_text_before(first First) string {
	if first.any {
		return '\t\treturn Match{\n\t\t\tnext: i + 1\n\t\t}\n'
	}
	mut out := strings.new_builder(256)
	out.writeln('\t\tmut j := i + 1')
	out.writeln('\t\tfor j < m.next && !(${or_join(first.classes.map(class_cond(it, 'r[j]')))}) {')
	out.writeln('\t\t\tj++')
	out.writeln('\t\t}')
	out.writeln('\t\treturn Match{\n\t\t\tnext: j\n\t\t}')
	return out.str()
}

// context_fn emits the function that tries a context's rules, in order, at
// one position
fn (mut gen Gen) context_fn(index int) !string {
	ctx := gen.g.contexts[index]
	mut nodes := []Node{}
	for rule in ctx.rules {
		nodes << parse_pattern(rule.pattern) or { return error('context "${ctx.name}": ${err}') }
	}
	plans := plan_shared_matches(nodes)
	mut body := strings.new_builder(4096)
	mut uses_c := false
	mut memo_vars := map[string]string{}
	// skip_classes are the runes a rule could start at; when every rule has
	// some, plain text is skipped up to the next of them in one go
	mut skip_classes := []Node{}
	mut can_skip := true
	firsts := nodes.map(first_of(it))
	for ri, rule in ctx.rules {
		if firsts[ri].nullable && rule.op.len == 0 {
			return error('context "${ctx.name}": rule "${rule.pattern}" can match nothing, so it needs to push, set or pop')
		}
	}
	table := first_rune_table(firsts)
	for ri, rule in ctx.rules {
		node := nodes[ri]
		plan := plans[ri]
		first := firsts[ri]
		bol := starts_at_bol(node)
		mut guards := []string{}
		if bol {
			guards << 'i == 0'
		}
		// a rule that can start at any rune leaves no plain text to skip
		starts_anywhere := first.nullable || first.any
		if starts_anywhere && !bol {
			can_skip = false
		}
		if !starts_anywhere {
			guards << if table.bits.len > 0 {
				'f & ${table.bits[ri]} != 0'
			} else {
				or_join(first.classes.map(class_cond(it, 'c')))
			}
			uses_c = true
			if !bol {
				skip_classes << first.classes
			}
		}
		// each rule is in a block of its own, so the `e` each declares doesn't
		// clash with another's
		indent := '\t\t'
		body.writeln('\t// ${rule.pattern.replace('\n', ' ')}')
		body.writeln(guarded_block(guards))
		gen.match_end(mut body, indent, node, plan, mut memo_vars)
		body.writeln('${indent}if e >= 0 {')
		scope := if rule.scope.len > 0 { rule.scope } else { ctx.scope }
		gen.rule_return(mut body, indent, index, ctx.rules, plans, ri, scope)
		body.writeln('${indent}}')
		body.writeln('\t}')
	}
	body.write_string(gen.plain_text_skip(ctx.name, can_skip, skip_classes, table, nodes))
	mut out := strings.new_builder(4096)
	if table.bits.len > 0 {
		gen.first_table(ctx.name, table, firsts)
	}
	out.writeln('// context ${ctx.name}')
	out.writeln('@[direct_array_access]')
	params := if gen.uses_emit[index] { 'r []rune, i int, emit bool' } else { 'r []rune, i int' }
	out.writeln('fn ${gen.ctx_fn_name(index)}(${params}) Match {')
	if uses_c {
		out.writeln('\tc := r[i]')
	}
	if uses_c && table.bits.len > 0 {
		// a rune past ASCII is looked up in the wide table, if there is one
		wide := if table.wide.len > 0 {
			'${gen.prefix}first_wide_${ctx.name}(c)'
		} else {
			'${table.mask_type}(0)'
		}
		out.writeln('\tf := if c < 128 { ${gen.prefix}first_${ctx.name}[c] } else { ${wide} }')
	}
	mut memo_names := memo_vars.values()
	memo_names.sort()
	for v in memo_names {
		out.writeln('\tmut ${v} := -2')
	}
	out.write_string(body.str())
	out.writeln('}\n')
	return out.str()
}

// FirstTable gives each rule of a context a bit, set for the ASCII runes its
// match can start with, so a rule's guard is one bit test rather than a run of
// comparisons
// match_end writes the code that sets `e` to where a rule's pattern, `node`,
// ends at i, or -1. With `plan` shared, the head of the pattern is matched
// once, into a variable from `memo_vars`, and shared with the other rules in
// the context that start the same way.
fn (mut gen Gen) match_end(mut body strings.Builder, indent string, node Node, plan SharedMatch, mut memo_vars map[string]string) {
	if !plan.shared {
		body.writeln('${indent}e := ${gen.pattern_fn(node)}(r, i)')
		return
	}
	head_fn := gen.pattern_fn(plan.head)
	v := memo_vars[node_key(plan.head)] or {
		name := 'h${memo_vars.len}'
		memo_vars[node_key(plan.head)] = name
		name
	}
	mut pre_cond := ''
	if pre := plan.pre {
		pre_cond = '${gen.pattern_fn(pre)}(r, i) >= 0 && '
	}
	body.writeln('${indent}if ${pre_cond}${v} == -2 {')
	body.writeln('${indent}\t${v} = ${head_fn}(r, i)')
	body.writeln('${indent}}')
	if plan.pre == none && plan.tail == none {
		body.writeln('${indent}e := ${v}')
		return
	}
	mut end_expr := v
	if tail := plan.tail {
		end_expr = '${gen.pattern_fn(tail)}(r, ${v})'
	}
	body.writeln('${indent}e := if ${pre_cond}${v} >= 0 { ${end_expr} } else { -1 }')
}

// rule_return writes what rule `ri` of `rules` returns once its pattern has
// matched up to `e`: its match with `scope`, or for a word list rule, the
// scope of the word matched, if it's one of them
fn (mut gen Gen) rule_return(mut body strings.Builder, indent string, index int, rules []Rule, plans []SharedMatch, ri int, scope string) {
	rule := rules[ri]
	if !rule.words {
		body.writeln('${indent}\treturn ${gen.match_lit('e', '.' + scope_ident(scope), rule)}')
		return
	}
	if skips_words_without_emit(rules, plans, ri) {
		gen.uses_emit[index] = true
		body.writeln('${indent}\tif !emit {')
		body.writeln('${indent}\t\treturn Match{\n\t\t\tend: e\n\t\t}')
		body.writeln('${indent}\t}')
	}
	body.writeln('${indent}\ts := ${gen.prefix}words(r, i, e)')
	body.writeln('${indent}\tif s != .none {')
	body.writeln('${indent}\t\treturn ${gen.match_lit('e', 's', rule)}')
	body.writeln('${indent}\t}')
}

// plain_text_skip is how context `name` returns when none of its rules
// match: with `can_skip`, as plain text up to the next rune one could start
// at, looked up in `table` when there is one, or else tested against
// `skip_classes`. Without, it's one rune of plain text.
fn (gen Gen) plain_text_skip(name string, can_skip bool, skip_classes []Node, table FirstTable, nodes []Node) string {
	if !can_skip {
		return '\treturn Match{\n\t\tnext: i + 1\n\t}\n'
	}
	if skip_classes.len == 0 {
		// no rules at all: the rest of the line is plain text
		return '\treturn Match{\n\t\tnext: r.len\n\t}\n'
	}
	mut stop := 'if ${or_join(dedupe_classes(skip_classes).map(class_cond(it, 'x')))} {'
	if table.bits.len > 0 {
		// the rules that can start past the line's first rune
		mut skip_bits := u64(0)
		for ri, b in table.bits {
			if b != 0 && !starts_at_bol(nodes[ri]) {
				skip_bits |= b
			}
		}
		stop = 'if x < 128 && ${gen.prefix}first_${name}[x] & ${skip_bits} != 0 {'
		if table.wide.len > 0 {
			stop = 'if (if x < 128 { ${gen.prefix}first_${name}[x] } else { ${gen.prefix}first_wide_${name}(x) }) & ${skip_bits} != 0 {'
		}
	}
	mut out := strings.new_builder(512)
	out.writeln('\tmut j := i + 1')
	out.writeln('\tfor j < r.len {')
	out.writeln('\t\tx := r[j]')
	out.writeln('\t\t${stop}')
	out.writeln('\t\t\tbreak')
	out.writeln('\t\t}')
	out.writeln('\t\tj++')
	out.writeln('\t}')
	out.writeln('\treturn Match{\n\t\tnext: j\n\t}')
	return out.str()
}

struct FirstTable {
	// bits is each rule's bit, 0 for a rule that can't be guarded
	bits []u64
	// ascii is, for each ASCII rune, the bits of the rules it can start
	ascii []u64
	// wide are the rules that can start with a rune past ASCII, tested one by
	// one for those runes
	wide      []int
	mask_type string
}

// min_table_rules is how many guarded rules a context needs before a table
// beats testing their first runes one by one
const min_table_rules = 3

fn first_rune_table(firsts []First) FirstTable {
	mut bits := []u64{len: firsts.len}
	mut n := 0
	for ri, f in firsts {
		if !f.nullable && !f.any {
			if n == 64 {
				return FirstTable{}
			}
			bits[ri] = u64(1) << n
			n++
		}
	}
	if n < min_table_rules {
		return FirstTable{}
	}
	mut ascii := []u64{len: 128}
	mut wide := []int{}
	for ri, f in firsts {
		if bits[ri] == 0 {
			continue
		}
		for ch in 0 .. 128 {
			if f.classes.any(class_contains(it, rune(ch))) {
				ascii[ch] |= bits[ri]
			}
		}
		if f.classes.any(class_reaches_past_ascii(it)) {
			wide << ri
		}
	}
	return FirstTable{
		bits:      bits
		ascii:     ascii
		wide:      wide
		mask_type: if n <= 32 { 'u32' } else { 'u64' }
	}
}

// first_table emits a context's table, and the function giving the bits for a
// rune past ASCII if any rule can start with one
fn (mut gen Gen) first_table(name string, table FirstTable, firsts []First) {
	t := table.mask_type
	mut f := strings.new_builder(4096)
	f.writeln('const ${gen.prefix}first_${name} = [${table.ascii.map('${t}(${it})').join(', ')}]!\n')
	if table.wide.len > 0 {
		f.writeln('@[direct_array_access]')
		f.writeln('fn ${gen.prefix}first_wide_${name}(c rune) ${t} {')
		f.writeln('\tmut f := ${t}(0)')
		for ri in table.wide {
			f.writeln('\tif ${or_join(dedupe_classes(firsts[ri].classes).map(class_cond(it, 'c')))} {')
			f.writeln('\t\tf |= ${table.bits[ri]}')
			f.writeln('\t}')
		}
		f.writeln('\treturn f')
		f.writeln('}\n')
	}
	gen.fns << f.str()
}

fn class_contains(node Node, ch rune) bool {
	if node.is_any() {
		return true
	}
	inside := node.ranges.any(ch >= it.lo && ch <= it.hi)
	return inside != node.negated
}

// class_reaches_past_ascii reports whether a class can match a rune past ASCII
fn class_reaches_past_ascii(node Node) bool {
	return node.negated || node.ranges.any(it.hi >= 128)
}

// dedupe_classes drops classes that repeat one before them, which the first
// runes of a context's rules often do
fn dedupe_classes(classes []Node) []Node {
	mut out := []Node{}
	mut seen := map[string]bool{}
	for c in classes {
		key := node_key(c)
		if key !in seen {
			seen[key] = true
			out << c
		}
	}
	return out
}

// SharedMatch is how a rule's pattern is matched: whole, or as a head that
// other rules in the context share, followed by its own tail
struct SharedMatch {
	shared bool
	// pre is a zero-width check before the head, like the `(?=[A-Z])` of a
	// type rule
	pre  ?Node
	head Node
	tail ?Node
	// same_end is set when the rule's match always ends where its head does:
	// everything around the head is zero-width
	same_end bool
}

// plan_shared_matches finds the rules whose pattern, or the start of it, is
// another rule's whole pattern. Identifier rules are the common case: a
// words rule, a call rule (the identifier then `(?=\()`) and a plain
// identifier rule all begin by matching the same identifier, which then
// only needs scanning once.
fn plan_shared_matches(nodes []Node) []SharedMatch {
	whole := nodes.map(node_key(it))
	mut plans := []SharedMatch{len: nodes.len}
	mut uses := map[string]int{}
	for i, node in nodes {
		if whole.count(it == whole[i]) > 1 {
			plans[i] = SharedMatch{
				shared:   true
				head:     node
				same_end: true
			}
			uses[whole[i]]++
			continue
		}
		if node.kind != .seq {
			continue
		}
		// leading zero-width checks stay in front of the shared head
		mut lead := 0
		for lead < node.kids.len && node.kids[lead].kind in [.look, .bol] {
			lead++
		}
		// the head is everything after the leading checks, or less; a whole
		// pattern with nothing in front is only shared when it's identical,
		// which was handled above
		for j := if lead > 0 { node.kids.len } else { node.kids.len - 1 }; j > lead; j-- {
			head := seq_of(node.kids[lead..j])
			if node_key(head) !in whole {
				continue
			}
			rest := node.kids[j..]
			plans[i] = SharedMatch{
				shared:   true
				pre:      if lead > 0 { ?Node(seq_of(node.kids[..lead])) } else { none }
				head:     head
				tail:     if rest.len > 0 { ?Node(seq_of(rest)) } else { none }
				same_end: rest.all(it.kind in [.look, .bol, .eol])
			}
			uses[node_key(head)]++
			break
		}
	}
	// a head only one rule uses gains nothing from being shared
	for i, plan in plans {
		key := node_key(plan.head)
		if plan.shared && (plan.tail != none || plan.pre != none)
			&& uses[key] + whole.count(it == key) < 2 {
			plans[i] = SharedMatch{}
		}
	}
	return plans
}

fn seq_of(kids []Node) Node {
	if kids.len == 1 {
		return kids[0]
	}
	return Node{
		kind: .seq
		kids: kids
	}
}

// skips_words_without_emit reports whether, when tokens aren't wanted, the
// words rule at `w` can return its match without looking the word up. That
// holds when a later rule matches the same text with no stack change, and
// every rule between ends in the same place with no stack change: then the
// lookup only decides the scope, which nobody is going to read.
fn skips_words_without_emit(rules []Rule, plans []SharedMatch, w int) bool {
	if rules[w].op.len > 0 || !plans[w].shared || plans[w].pre != none || plans[w].tail != none {
		return false
	}
	key := node_key(plans[w].head)
	for k in w + 1 .. rules.len {
		plan := plans[k]
		if rules[k].op.len > 0 || !plan.shared || !plan.same_end || node_key(plan.head) != key {
			return false
		}
		if !rules[k].words && plan.pre == none && plan.tail == none {
			return true
		}
	}
	return false
}

// node_key identifies a pattern by its structure, so equal patterns written
// differently (`\d` and `[0-9]`) share a matcher
fn node_key(n Node) string {
	mut parts := ['${n.kind}', n.negated.str(), '${n.min},${n.max}']
	for r in n.ranges {
		parts << '${u32(r.lo)}-${u32(r.hi)}'
	}
	for kid in n.kids {
		parts << '(${node_key(kid)})'
	}
	return parts.join(' ')
}

fn (gen Gen) match_lit(end string, scope string, rule Rule) string {
	mut fields := ['end: ${end}', 'scope: ${scope}']
	if rule.op.len > 0 {
		fields << 'op: .${rule.op}'
	}
	if rule.embed.len > 0 {
		fields << 'target: ${rule.embed_root}'
	}
	if rule.embed.len == 0 && rule.target.len > 0 {
		fields << 'target: ${gen.g.context_index(rule.target) or { 0 }}'
	}
	return 'Match{\n${fields.map('\t\t\t' + it).join('\n')}\n\t\t}'
}

// words_fn emits the word list lookup: hash the text, switch on the hash,
// then compare the runes of the word (or words) with that hash. Nothing is
// allocated.
fn (mut gen Gen) words_fn() {
	mut by_hash := map[u32][]string{}
	mut max_len := 0
	for word in sorted_keys(gen.g.words) {
		by_hash[fnv1a(word.runes())] << word
		max_len = int_max(max_len, word.runes().len)
	}
	mut hashes := by_hash.keys()
	hashes.sort()
	gen.out.writeln('@[direct_array_access]')
	gen.out.writeln('fn ${gen.prefix}words(r []rune, start int, end int) Scope {')
	gen.out.writeln('\tn := end - start')
	gen.out.writeln('\tif n > ${max_len} {')
	gen.out.writeln('\t\treturn .none')
	gen.out.writeln('\t}')
	gen.out.writeln('\tmut h := u32(${fnv_offset})')
	gen.out.writeln('\tfor k in start .. end {')
	gen.out.writeln('\t\th = (h ^ u32(r[k])) * ${fnv_prime}')
	gen.out.writeln('\t}')
	gen.out.writeln('\treturn match h {')
	for h in hashes {
		mut arms := []string{}
		for word in by_hash[h] {
			runes := word.runes()
			mut conds := ['n == ${runes.len}']
			for k, c in runes {
				conds << 'r[start + ${k}] == ${rune_lit(c)}'
			}
			arms << 'if ${conds.join(' && ')} { Scope.${scope_ident(gen.g.words[word])} }'
		}
		gen.out.writeln('\t\t${h} { ${arms.join(' else ')} else { Scope.none } }')
	}
	gen.out.writeln('\t\telse { Scope.none }')
	gen.out.writeln('\t}')
	gen.out.writeln('}\n')
}

const fnv_offset = u32(2166136261)
const fnv_prime = u32(16777619)

// fnv1a is the hash the generated words functions compute over a word's runes
fn fnv1a(runes []rune) u32 {
	mut h := fnv_offset
	for c in runes {
		h = (h ^ u32(c)) * fnv_prime
	}
	return h
}

// pattern_fn returns the matcher for a pattern: a function taking the line
// and a start position, returning where the match ends or -1
fn (mut gen Gen) pattern_fn(node Node) string {
	key := node_key(node)
	if name := gen.pattern_fns[key] {
		return name
	}
	name := gen.node_fn(node)
	gen.pattern_fns[key] = name
	return name
}

struct FnBody {
mut:
	lines   []string
	mutates bool
	vars    int
}

fn (mut b FnBody) line(s string) {
	b.lines << '\t' + s
}

fn (mut b FnBody) var(stem string) string {
	b.vars++
	return '${stem}${b.vars}'
}

fn (mut gen Gen) node_fn(node Node) string {
	name := '${gen.prefix}m${gen.fn_count}'
	gen.fn_count++
	mut b := FnBody{}
	gen.emit(node, mut b)
	mut f := strings.new_builder(1024)
	f.writeln('@[direct_array_access]')
	f.writeln('fn ${name}(r []rune, start int) int {')
	f.writeln(if b.mutates { '\tmut p := start' } else { '\tp := start' })
	for l in b.lines {
		f.writeln(l)
	}
	f.writeln('\treturn p')
	f.writeln('}\n')
	gen.fns << f.str()
	return name
}

// emit writes the statements that match `node` at p, advancing p past it or
// returning -1
fn (mut gen Gen) emit(node Node, mut b FnBody) {
	match node.kind {
		.class {
			b.line(if node.is_any() {
				'if p >= r.len {'
			} else {
				'if p >= r.len || !(${class_cond(node, 'r[p]')}) {'
			})
			b.line('\treturn -1')
			b.line('}')
			b.line('p++')
			b.mutates = true
		}
		.seq {
			for kid in node.kids {
				gen.emit(kid, mut b)
			}
		}
		.alt {
			subs := node.kids.map(gen.node_fn(it))
			q := b.var('q')
			b.line('mut ${q} := ${subs[0]}(r, p)')
			for sub in subs[1..] {
				b.line('if ${q} < 0 {')
				b.line('\t${q} = ${sub}(r, p)')
				b.line('}')
			}
			b.line('if ${q} < 0 {')
			b.line('\treturn -1')
			b.line('}')
			b.line('p = ${q}')
			b.mutates = true
		}
		.rep {
			gen.emit_rep(node, mut b)
		}
		.look {
			sub := gen.node_fn(node.kids[0])
			b.line('if ${sub}(r, p) ${if node.negated { '>=' } else { '<' }} 0 {')
			b.line('\treturn -1')
			b.line('}')
		}
		.bol {
			b.line('if p != 0 {')
			b.line('\treturn -1')
			b.line('}')
		}
		.eol {
			b.line('if p != r.len {')
			b.line('\treturn -1')
			b.line('}')
		}
	}
}

fn (mut gen Gen) emit_rep(node Node, mut b FnBody) {
	kid := node.kids[0]
	counted := node.min > 1 || node.max >= 0
	n := if counted { b.var('n') } else { '' }
	if counted {
		b.line('mut ${n} := 0')
	}
	if node.min == 1 && !counted {
		// one required, then any number more
		gen.emit(kid, mut b)
	}
	gen.emit_rep_loop(node, n, counted, mut b)
	b.mutates = true
	if counted && node.min > 0 {
		b.line('if ${n} < ${node.min} {')
		b.line('\treturn -1')
		b.line('}')
	}
}

// emit_rep_loop writes the loop that matches `node`'s kid as many more
// times as it can, counting them in `n` when `counted`. A class is matched
// inline, rune by rune; anything else through its own function, until it
// matches nothing more.
fn (mut gen Gen) emit_rep_loop(node Node, n string, counted bool, mut b FnBody) {
	kid := node.kids[0]
	if kid.kind == .class {
		mut conds := ['p < r.len']
		if counted && node.max >= 0 {
			conds << '${n} < ${node.max}'
		}
		if !kid.is_any() {
			conds << class_cond(kid, 'r[p]')
		}
		b.line('for ${and_join(conds)} {')
		b.line('\tp++')
		if counted {
			b.line('\t${n}++')
		}
		b.line('}')
		return
	}
	sub := gen.node_fn(kid)
	q := b.var('q')
	b.line(if counted && node.max >= 0 { 'for ${n} < ${node.max} {' } else { 'for {' })
	b.line('\t${q} := ${sub}(r, p)')
	b.line('\tif ${q} < 0 || ${q} == p {')
	b.line('\t\tbreak')
	b.line('\t}')
	b.line('\tp = ${q}')
	if counted {
		b.line('\t${n}++')
	}
	b.line('}')
}

// class_cond is a V boolean expression testing whether the rune `x` is in
// the class
fn class_cond(node Node, x string) string {
	if node.is_any() {
		return 'true'
	}
	mut parts := []string{}
	for r in node.ranges {
		if r.lo == r.hi {
			parts << '${x} == ${rune_lit(r.lo)}'
			continue
		}
		parts << '${x} >= ${rune_lit(r.lo)} && ${x} <= ${rune_lit(r.hi)}'
	}
	joined := or_join(parts)
	if node.negated {
		return '!(${joined})'
	}
	return joined
}

// or_join joins conditions with ||, bracketing the ones that contain &&, as
// V requires
fn or_join(conds []string) string {
	if conds.len == 1 {
		return conds[0]
	}
	return conds.map(if it.contains(' && ') { '(${it})' } else { it }).join(' || ')
}

// and_join joins conditions with &&, bracketing the ones that contain ||
fn and_join(conds []string) string {
	if conds.len == 1 {
		return conds[0]
	}
	return conds.map(if it.contains(' || ') { '(${it})' } else { it }).join(' && ')
}

fn rune_lit(r rune) string {
	if r >= ` ` && r <= `~` && r != `\\` && r != 96 {
		return '`${r}`'
	}
	return 'rune(${u32(r)})'
}

fn scope_ident(scope string) string {
	return if scope.len == 0 { 'none' } else { scope.replace('.', '_') }
}

fn v_str(s string) string {
	return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"
}

fn v_str_array(items []string) string {
	if items.len == 0 {
		return '[]string{}'
	}
	return '[' + items.map(v_str(it)).join(', ') + ']'
}

fn sorted_keys[T](m map[string]T) []string {
	mut keys := m.keys()
	keys.sort()
	return keys
}

// generate_registry emits the Lang enum and the dispatch from a Lang to its
// generated lexer
fn generate_registry(grammars []Grammar, takes_emit []bool, license string) string {
	mut out := strings.new_builder(4096)
	out.write_string(license)
	out.write_string('\n${header_note}\n\nmodule syntax\n\n')
	out.writeln('// Lang picks a generated lexer. plain lexes nothing.')
	out.writeln('pub enum Lang as u8 {')
	out.writeln('\tplain')
	for g in grammars {
		out.writeln('\t${g.id}')
	}
	out.writeln('}\n')
	out.writeln('const builtin_syntaxes = [${grammars.map('lex_${it.id}_syntax').join(', ')}]\n')
	out.writeln('fn lang_info(lang Lang) LangInfo {')
	out.writeln('\treturn match lang {')
	out.writeln('\t\t.plain { plain_info }')
	for g in grammars {
		out.writeln('\t\t.${g.id} { lex_${g.id}_info }')
	}
	out.writeln('\t}')
	out.writeln('}\n')
	out.writeln('@[inline]')
	out.writeln('fn lang_step(lang Lang, ctx u8, r []rune, i int, emit bool) Match {')
	out.writeln('\treturn match lang {')
	out.writeln('\t\t.plain { Match{\n\t\t\tnext: r.len\n\t\t} }')
	for k, g in grammars {
		args := if takes_emit[k] { 'ctx, r, i, emit' } else { 'ctx, r, i' }
		out.writeln('\t\t.${g.id} { lex_${g.id}_step(${args}) }')
	}
	out.writeln('\t}')
	out.writeln('}')
	return out.str()
}
